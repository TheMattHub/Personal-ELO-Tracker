def translate_text(lang: str, key: str, **kwargs) -> str:
    text = repair_text_encoding(TRANSLATIONS.get(lang, {}).get(key, key))
    if kwargs:
        safe_kwargs = {
            name: repair_text_encoding(value) if isinstance(value, str) else value
            for name, value in kwargs.items()
        }
        return text.format(**safe_kwargs)
    return text


def translate_html(lang: str, html: str) -> str:
    html = repair_text_encoding(html)
    if lang == "en":
        return html
    replacements = TRANSLATIONS.get(lang, {})
    for source in sorted(replacements, key=len, reverse=True):
        html = html.replace(source, repair_text_encoding(replacements[source]))
    for pattern, replacer in REGEX_TRANSLATIONS.get(lang, []):
        html = pattern.sub(lambda match: repair_text_encoding(replacer(match)), html)
    return repair_text_encoding(html)


def repair_text_encoding(text: str) -> str:
    if not text or not any(marker in text for marker in MOJIBAKE_MARKERS):
        return text

    repaired = text
    for _ in range(3):
        updated = _decode_mojibake_once(repaired)
        if updated == repaired:
            break
        repaired = updated
        if not any(marker in repaired for marker in MOJIBAKE_MARKERS):
            break
    return repaired


def _decode_mojibake_once(text: str) -> str:
    for source_encoding in ("cp1252", "latin-1"):
        try:
            return text.encode(source_encoding).decode("utf-8")
        except UnicodeError:
            continue
    return text


